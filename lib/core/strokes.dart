/// Stroke-order data for tracing. Each letter is a list of strokes, each stroke
/// a list of points in a 0..1 box (y grows downward), in the order a child
/// should draw them. Built from straight lines and arcs.
typedef Stroke = List<Offset>;

const double _t = 0.12, _b = 0.88; // capital top / baseline
const double _x = 0.45, _bl = 0.82, _asc = 0.12, _dsc = 0.97; // small letters

List<Offset> L(double x1, double y1, double x2, double y2) {
  final d = sqrt(pow(x2 - x1, 2) + pow(y2 - y1, 2));
  final n = max(2, (d / 0.02).ceil());
  return [for (var i = 0; i <= n; i++) Offset(x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n)];
}

/// Arc around (cx,cy) with radii rx,ry from [start] degrees, turning [sweep]
/// degrees (positive = clockwise on screen). 0° = right, 90° = down.
List<Offset> A(double cx, double cy, double rx, double ry, double start, double sweep) {
  final n = max(4, (sweep.abs() / 6).ceil());
  return [
    for (var i = 0; i <= n; i++)
      Offset(cx + rx * cos((start + sweep * i / n) * pi / 180), cy + ry * sin((start + sweep * i / n) * pi / 180))
  ];
}

